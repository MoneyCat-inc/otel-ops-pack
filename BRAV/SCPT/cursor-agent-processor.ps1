function Remove-CompletedTask {
    param([string]$TaskId)
    
    try {
        $queueFile = "$AgentDir/task_queue.json"
        $queue = Get-Content $queueFile | ConvertFrom-Json
        
        # Remove completed task
        $updatedQueue = $queue | Where-Object { $_.id -ne $TaskId }
        
        # Save updated queue
        $updatedQueue | ConvertTo-Json -Depth 10 | Set-Content $queueFile -Encoding UTF8
        
        Write-ColorOutput "   🗑️ Removed completed task: $TaskId" "Gray"
    } catch {
        Write-ColorOutput "   ⚠️ Failed to remove completed task: $($_.Exception.Message)" "Yellow"
    }
}

function Show-TaskList {
    $queue = Get-TaskQueue
    if ($queue.Count -eq 0) {
        Write-ColorOutput "📋 No tasks in queue" "Yellow"
        return
    }
    
    Write-ColorOutput "📋 Task Queue ($($queue.Count) tasks)" "Cyan"
    Write-ColorOutput ("=" * 50) "Gray"
    
    foreach ($task in $queue | Sort-Object priority -Descending) {
        $priorityColor = switch ($task.priority) {
            {$_ -ge 9} { "Red" }
            {$_ -ge 7} { "Yellow" }
            {$_ -ge 5} { "Green" }
            default { "Gray" }
        }
        
        Write-ColorOutput "ID: $($task.id)" "White"
        Write-ColorOutput "  Priority: $($task.priority)" $priorityColor
        Write-ColorOutput "  Type: $($task.type)" "Gray"
        Write-ColorOutput "  Description: $($task.payload.description)" "White"
        Write-ColorOutput "  Files: $($task.payload.files -join ', ')" "Gray"
        Write-ColorOutput "  Created: $($task.createdAt)" "Gray"
        Write-ColorOutput ""
    }
}

function Process-SingleTask {
    param([string]$TaskId)
    
    $queue = Get-TaskQueue
    $task = $queue | Where-Object { $_.id -eq $TaskId }
    
    if (-not $task) {
        Write-ColorOutput "❌ Task not found: $TaskId" "Red"
        return
    }
    
    $config = Get-AgentConfig
    if (-not $config) { return }
    
    if (-not (Test-AgentLock)) { return }
    
    Write-ColorOutput "🎯 Processing single task: $TaskId" "Cyan"
    Process-Task -Task $task -Config $config
    Update-AgentState -Status "completed" -JobsProcessed 1
}

function Process-AllTasks {
    $config = Get-AgentConfig
    $queue = Get-TaskQueue
    
    if (-not $config) { return }
    if (-not (Test-AgentLock)) { return }
    
    # Inject recurring jobs before processing
    Write-ColorOutput "🔄 Injecting recurring maintenance jobs..." "Cyan"
    try {
        $injectorScript = "scripts/agent/recurring-job-injector.ps1"
        if (Test-Path $injectorScript) {
            $injectResult = & pwsh -File $injectorScript -Verbose:$Verbose
            Write-VerboseOutput "Recurring injection completed"
        } else {
            Write-VerboseOutput "Recurring injector not found, skipping"
        }
    } catch {
        Write-VerboseOutput "Recurring injection failed: $($_.Exception.Message)"
    }
    
    # Refresh queue after injection
    $queue = Get-TaskQueue
    
    Write-ColorOutput "🚀 Processing all tasks in queue..." "Cyan"
    Write-ColorOutput "Max concurrent jobs: $($config.maxJobs)" "Gray"
    
    $processedCount = 0
    $highPriorityTasks = $queue | Where-Object { $_.priority -ge 7 } | Sort-Object priority -Descending
    
    foreach ($task in $highPriorityTasks) {
        if ($processedCount -ge $config.maxJobs) {
            Write-ColorOutput "⏸️  Reached max jobs limit ($($config.maxJobs))" "Yellow"
            break
        }
        
        $success = Process-Task -Task $task -Config $config
        if ($success) {
            $processedCount++
        }
    }
    
    Update-AgentState -Status "completed" -JobsProcessed $processedCount
    Write-ColorOutput "🎉 Processing complete! Jobs processed: $processedCount" "Green"
}

# Main execution
Write-VerboseOutput "Starting cursor-agent-processor with parameters: ProcessAll=$ProcessAll, ListTasks=$ListTasks, TaskId=$TaskId, DryRun=$DryRun"

if ($ListTasks) {
    Show-TaskList
} elseif ($TaskId) {
    Process-SingleTask -TaskId $TaskId
} elseif ($ProcessAll) {
    Process-AllTasks
} else {
    Write-ColorOutput "cursor-agent-processor.ps1" "Cyan"
    Write-ColorOutput "Advanced task processing for cursor-gap-closer agent" "White"
    Write-ColorOutput ""
    Write-ColorOutput "Usage:" "Yellow"
    Write-ColorOutput "  -ListTasks     Show all tasks in queue" "White"
    Write-ColorOutput "  -TaskId <id>   Process specific task" "White"
    Write-ColorOutput "  -ProcessAll    Process all high-priority tasks" "White"
    Write-ColorOutput "  -DryRun        Show what would be done without making changes" "White"
    Write-ColorOutput "  -Verbose       Show detailed output" "White"
    Write-ColorOutput ""
    Write-ColorOutput "Examples:" "Yellow"
    Write-ColorOutput "  pnpm cursor:list-tasks" "White"
    Write-ColorOutput "  pnpm cursor:task task-a11y-001" "White"
    Write-ColorOutput "  pnpm cursor:process-all" "White"
}
