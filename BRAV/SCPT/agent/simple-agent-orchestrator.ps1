$agentConfigs = @(
    @{
        id = "monitoring-agent"
        name = "Monitoring Agent"
        taskType = "monitoring"
        maxConcurrency = 5
        script = "monitoring-agent.ps1"
    },
    @{
        id = "cleanup-agent"
        name = "Cleanup Agent"
        taskType = "cleanup"
        maxConcurrency = 3
        script = "cleanup-agent.ps1"
    },
    @{
        id = "remediation-agent"
        name = "Remediation Agent"
        taskType = "remediation"
        maxConcurrency = 2
        script = "remediation-agent.ps1"
    },
    @{
        id = "maintenance-agent"
        name = "Maintenance Agent"
        taskType = "maintenance"
        maxConcurrency = 4
        script = "maintenance-agent.ps1"
    },
    @{
        id = "alert-agent"
        name = "Alert Agent"
        taskType = "alert"
        maxConcurrency = 10
        script = "alert-agent.ps1"
    },
    @{
        id = "optimization-agent"
        name = "Optimization Agent"
        taskType = "optimization"
        maxConcurrency = 1
        script = "optimization-agent.ps1"
    },
    @{
        id = "compliance-agent"
        name = "Compliance Agent"
        taskType = "compliance"
        maxConcurrency = 2
        script = "compliance-agent.ps1"
    }
)

# Global variables
$global:agents = @{}
$global:behaviorData = @{}
$global:reports = @()
$global:isRunning = $false

# Function to create agent stub scripts
function New-AgentStub {
    param([hashtable]$Config)
    
    $stubContent = @"
#!/usr/bin/env pwsh

# $($Config.name) - Background Agent
# Generated by Simple Agent Orchestrator

param(
    [string]`$AgentId = "$($Config.id)",
    [string]`$TaskType = "$($Config.taskType)",
    [int]`$MaxConcurrency = $($Config.maxConcurrency)
)

`$ErrorActionPreference = "Continue"

# Agent state
`$agentState = @{
    id = `$AgentId
    taskType = `$TaskType
    isRunning = `$true
    taskCount = 0
    successCount = 0
    errorCount = 0
    startTime = Get-Date
}

function Write-AgentLog {
    param([string]`$Message, [string]`$Level = "INFO")
    `$timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    `$logMessage = "[`$timestamp] [`$Level] [`$AgentId] `$Message"
    Write-Host `$logMessage
}

function Process-Task {
    param([string]`$TaskId)
    
    `$agentState.taskCount++
    
    try {
        Write-AgentLog "Processing `$TaskType task: `$TaskId" "INFO"
        
        # Simulate task work
        Start-Sleep -Milliseconds (Get-Random -Minimum 500 -Maximum 2000)
        
        # Simulate success/failure (90% success rate)
        `$success = (Get-Random -Minimum 1 -Maximum 10) -gt 1
        
        if (`$success) {
            `$agentState.successCount++
            Write-AgentLog "Task `$TaskId completed successfully" "SUCCESS"
            return `$true
        } else {
            `$agentState.errorCount++
            Write-AgentLog "Task `$TaskId failed" "ERROR"
            return `$false
        }
        
    } catch {
        `$agentState.errorCount++
        Write-AgentLog "Task `$TaskId error: `$(`$_.Exception.Message)" "ERROR"
        return `$false
    }
}

# Main agent loop
Write-AgentLog "Starting `$AgentId agent..." "INFO"

while (`$agentState.isRunning) {
    try {
        # Process multiple tasks based on concurrency
        `$tasksToProcess = Get-Random -Minimum 1 -Maximum (`$MaxConcurrency + 1)
        
        for (`$i = 0; `$i -lt `$tasksToProcess; `$i++) {
            `$taskId = "task-`$(Get-Date -Format 'yyyyMMddHHmmss')-`$i"
            Process-Task -TaskId `$taskId
        }
        
        # Sleep between task batches
        Start-Sleep -Seconds (Get-Random -Minimum 2 -Maximum 8)
        
    } catch {
        Write-AgentLog "Agent error: `$(`$_.Exception.Message)" "ERROR"
        Start-Sleep -Seconds 5
    }
}

Write-AgentLog "Agent `$AgentId stopped" "INFO"
"@

    $scriptPath = Join-Path $OutputDir $Config.script
    $stubContent | Out-File -FilePath $scriptPath -Encoding UTF8
    Write-Host "✅ Created agent stub: $scriptPath" -ForegroundColor Green
}

# Function to start an agent
function Start-Agent {
    param([hashtable]$Config)
    
    Write-Host "🤖 Starting $($Config.name)..." -ForegroundColor Yellow
    
    try {
        # Create agent stub if it doesn't exist
        $scriptPath = Join-Path $OutputDir $Config.script
        if (-not (Test-Path $scriptPath)) {
            New-AgentStub -Config $Config
        }
        
        # Start agent process
        $process = Start-Process -FilePath "pwsh" -ArgumentList @(
            "-File", $scriptPath,
            "-AgentId", $Config.id,
            "-TaskType", $Config.taskType,
            "-MaxConcurrency", $Config.maxConcurrency
        ) -PassThru -NoNewWindow -RedirectStandardOutput (Join-Path $OutputDir "logs\$($Config.id).log") -RedirectStandardError (Join-Path $OutputDir "logs\$($Config.id)-error.log")
        
        # Store agent reference
        $global:agents[$Config.id] = @{
            process = $process
            config = $Config
            startTime = Get-Date
            taskCount = 0
            successCount = 0
            errorCount = 0
        }
        
        # Initialize behavior tracking
        $global:behaviorData[$Config.id] = @{
            agentId = $Config.id
            totalTasks = 0
            successRate = 0
            avgDuration = 0
            failurePatterns = @()
            resourceUsage = @{
                avgMemory = 0
                peakMemory = 0
            }
            anomalies = @()
            recommendations = @()
        }
        
        Write-Host "✅ $($Config.name) started (PID: $($process.Id))" -ForegroundColor Green
        
    } catch {
        Write-Host "❌ Failed to start $($Config.name): $($_.Exception.Message)" -ForegroundColor Red
    }
}

# Function to monitor agents
function Start-Monitoring {
    param([int]$Duration)
    
    Write-Host "📊 Starting agent monitoring for $Duration minutes..." -ForegroundColor Cyan
    $global:isRunning = $true
    $endTime = (Get-Date).AddMinutes($Duration)
    
    while ((Get-Date) -lt $endTime -and $global:isRunning) {
        try {
            # Check agent health
            foreach ($agentId in $global:agents.Keys) {
                $agent = $global:agents[$agentId]
                
                if ($agent.process.HasExited) {
                    Write-Host "⚠️ Agent $agentId has exited (Code: $($agent.process.ExitCode))" -ForegroundColor Yellow
                    
                    # Restart if needed
                    if ($agent.config.restartOnFailure) {
                        Start-Agent -Config $agent.config
                    }
                }
            }
            
            # Collect metrics
            Collect-Metrics
            
            # Analyze behavior
            Analyze-Behavior
            
            # Generate reports
            Generate-ECRRReports
            
            Start-Sleep -Seconds 30
            
        } catch {
            Write-Host "⚠️ Error in monitoring loop: $($_.Exception.Message)" -ForegroundColor Yellow
            Start-Sleep -Seconds 10
        }
    }
    
    $global:isRunning = $false
    Write-Host "⏹️ Monitoring completed" -ForegroundColor Cyan
}

# Function to collect metrics
function Collect-Metrics {
    foreach ($agentId in $global:agents.Keys) {
        $agent = $global:agents[$agentId]
        $behavior = $global:behaviorData[$agentId]
        
        if ($agent.process -and -not $agent.process.HasExited) {
            try {
                # Get process memory usage
                $process = Get-Process -Id $agent.process.Id -ErrorAction SilentlyContinue
                if ($process) {
                    $memoryUsage = $process.WorkingSet64 / 1MB
                    
                    $behavior.resourceUsage.avgMemory = ($behavior.resourceUsage.avgMemory + $memoryUsage) / 2
                    $behavior.resourceUsage.peakMemory = [Math]::Max($behavior.resourceUsage.peakMemory, $memoryUsage)
                }
                
                # Count tasks from log file
                $logFile = Join-Path $OutputDir "logs\$agentId.log"
                if (Test-Path $logFile) {
                    $logContent = Get-Content $logFile -ErrorAction SilentlyContinue
                    $agent.taskCount = ($logContent | Where-Object { $_ -match "Processing.*task" }).Count
                    $agent.successCount = ($logContent | Where-Object { $_ -match "completed successfully" }).Count
                    $agent.errorCount = ($logContent | Where-Object { $_ -match "failed|ERROR" }).Count
                }
                
            } catch {
                # Skip if process not found
            }
        }
    }
}

# Function to analyze behavior
function Analyze-Behavior {
    foreach ($agentId in $global:behaviorData.Keys) {
        $behavior = $global:behaviorData[$agentId]
        $agent = $global:agents[$agentId]
        
        # Calculate success rate
        if ($agent.taskCount -gt 0) {
            $behavior.successRate = $agent.successCount / $agent.taskCount
        }
        
        # Detect anomalies
        $behavior.anomalies = @()
        if ($behavior.successRate -lt 0.8 -and $behavior.successRate -gt 0) {
            $behavior.anomalies += "Low success rate: $([Math]::Round($behavior.successRate * 100, 1))%"
        }
        
        if ($behavior.resourceUsage.peakMemory -gt 100) { # 100MB
            $behavior.anomalies += "High memory usage: $([Math]::Round($behavior.resourceUsage.peakMemory, 1))MB"
        }
        
        # Generate recommendations
        $behavior.recommendations = @()
        if ($behavior.successRate -lt 0.9 -and $behavior.successRate -gt 0) {
            $behavior.recommendations += "Investigate task failures"
        }
        if ($behavior.resourceUsage.peakMemory -gt 50) {
            $behavior.recommendations += "Monitor memory usage"
        }
        if ($agent.errorCount -gt 10) {
            $behavior.recommendations += "Review error patterns"
        }
    }
}

# Function to generate ECRR reports
function Generate-ECRRReports {
    $timestamp = Get-Date
    
    foreach ($agentId in $global:behaviorData.Keys) {
        $behavior = $global:behaviorData[$agentId]
        $agent = $global:agents[$agentId]
        
        $report = @{
            reportId = "ecrr-$agentId-$($timestamp.Ticks)"
            timestamp = $timestamp.ToString("yyyy-MM-dd HH:mm:ss")
            scope = "Agent Behavior Analysis: $agentId"
            findings = @{
                critical = $behavior.anomalies | Where-Object { $_ -match "High memory|Low success" }
                major = $behavior.anomalies | Where-Object { $_ -notmatch "High memory|Low success" }
                minor = $behavior.recommendations
            }
            recommendations = $behavior.recommendations
            compliance = @{
                security = $behavior.anomalies.Count -eq 0
                performance = $behavior.successRate -gt 0.8
                reliability = $behavior.resourceUsage.peakMemory -lt 100
            }
            evidence = @{
                logs = @("$OutputDir/logs/$agentId.log")
                metrics = @()
                screenshots = @()
            }
            responsibleAgent = $agentId
            bossCatApproval = $behavior.successRate -gt 0.9 -and $behavior.anomalies.Count -eq 0
            agentStats = @{
                taskCount = $agent.taskCount
                successCount = $agent.successCount
                errorCount = $agent.errorCount
                uptime = ((Get-Date) - $agent.startTime).TotalMinutes
            }
        }
        
        $global:reports += $report
        
        # Save report
        $reportPath = Join-Path $OutputDir "ecrr\$($report.reportId).json"
        $report | ConvertTo-Json -Depth 10 | Out-File -FilePath $reportPath -Encoding UTF8
        
        Write-Host "📋 Generated ECRR report: $($report.reportId)" -ForegroundColor Blue
    }
}

# Function to stop all agents
function Stop-AllAgents {
    Write-Host "🛑 Stopping all agents..." -ForegroundColor Yellow
    
    foreach ($agentId in $global:agents.Keys) {
        $agent = $global:agents[$agentId]
        
        if (-not $agent.process.HasExited) {
            Write-Host "🛑 Stopping $agentId..." -ForegroundColor Yellow
            $agent.process.Kill()
            $agent.process.WaitForExit(5000)
        }
    }
    
    $global:agents = @{}
    $global:isRunning = $false
    
    Write-Host "✅ All agents stopped" -ForegroundColor Green
}

# Function to display final status
function Show-FinalStatus {
    Write-Host "`n" -NoNewline
    Write-Host "🐾 " -ForegroundColor Cyan -NoNewline
    Write-Host "BossCat OEM - Final Agent Status" -ForegroundColor White
    Write-Host "=" * 60 -ForegroundColor Cyan
    
    $totalReports = $global:reports.Count
    $approvedReports = ($global:reports | Where-Object { $_.bossCatApproval }).Count
    $criticalFindings = ($global:reports | ForEach-Object { $_.findings.critical.Count } | Measure-Object -Sum).Sum
    
    Write-Host "📊 SUMMARY" -ForegroundColor Yellow
    Write-Host "  🤖 Agents Deployed: $($global:agents.Count)" -ForegroundColor Blue
    Write-Host "  📋 ECRR Reports: $totalReports" -ForegroundColor Blue
    Write-Host "  ✅ BossCat Approved: $approvedReports" -ForegroundColor Green
    Write-Host "  🚨 Critical Findings: $criticalFindings" -ForegroundColor Red
    
    Write-Host "`n🤖 AGENT PERFORMANCE" -ForegroundColor Yellow
    foreach ($agentId in $global:behaviorData.Keys) {
        $behavior = $global:behaviorData[$agentId]
        $agent = $global:agents[$agentId]
        
        $status = if ($behavior.successRate -gt 0.9) { "✅" } elseif ($behavior.successRate -gt 0.7) { "⚠️" } else { "❌" }
        $approval = if ($behavior.successRate -gt 0.9 -and $behavior.anomalies.Count -eq 0) { "APPROVED" } else { "REVIEW" }
        
        Write-Host "  $status $($agentId.PadRight(20)) Success: $([Math]::Round($behavior.successRate * 100, 1))% Tasks: $($agent.taskCount) $approval" -ForegroundColor White
    }
    
    # BossCat approval
    $overallApproval = $criticalFindings -eq 0 -and $totalReports -gt 0
    Write-Host "`n🐾 BOSSCAT OEM APPROVAL" -ForegroundColor Cyan
    Write-Host "-" * 60 -ForegroundColor Gray
    
    if ($overallApproval) {
        Write-Host "✅ MISSION APPROVED - All agents operating within parameters" -ForegroundColor Green
        Write-Host "🐾 BossCat OEM Signature: MISSION APPROVED" -ForegroundColor Green
    } else {
        Write-Host "⚠️ MISSION REQUIRES REVIEW - Issues detected" -ForegroundColor Yellow
        Write-Host "🐾 BossCat OEM Signature: REQUIRES REVIEW" -ForegroundColor Yellow
    }
    
    Write-Host "=" * 60 -ForegroundColor Cyan
}

# Main execution
try {
    Write-Host "`n" -NoNewline
    Write-Host "🐾 " -ForegroundColor Cyan -NoNewline
    Write-Host "BossCat OEM - Simple Background Agent Orchestrator" -ForegroundColor White
    Write-Host "=" * 70 -ForegroundColor Cyan
    Write-Host "📋 Mission: Spin off tasks to background agents and monitor behavior" -ForegroundColor Yellow
    Write-Host "⏱️  Duration: $Duration minutes" -ForegroundColor Yellow
    Write-Host "📁 Output: $OutputDir" -ForegroundColor Yellow
    Write-Host "=" * 70 -ForegroundColor Cyan
    
    # Start all agents
    foreach ($config in $agentConfigs) {
        Start-Agent -Config $config
        Start-Sleep -Seconds 1
    }
    
    # Start monitoring
    Start-Monitoring -Duration $Duration
    
    # Show final status
    Show-FinalStatus
    
} catch {
    Write-Host "❌ Mission failed: $($_.Exception.Message)" -ForegroundColor Red
} finally {
    Stop-AllAgents
}

Write-Host "🏁 Mission completed" -ForegroundColor Cyan
