}

function Cleanup-GPUIntegration {
    Write-ECRRLog "Cleaning up GPU integration..."
    
    if ($DryRun) {
        Write-ECRRLog "DRY RUN: Would clean up GPU integration"
        return $true
    }
    
    # Stop GPU sidecars
    try {
        docker-compose -f docker-compose.gpu.yml down
        Write-ECRRLog "GPU sidecars stopped"
    } catch {
        Write-ECRRLog "Failed to stop GPU sidecars: $($_.Exception.Message)" "ERROR"
    }
    
    # Stop monitoring processes
    try {
        $gpuProcesses = Get-Process -Name "pwsh" -ErrorAction SilentlyContinue | Where-Object { $_.CommandLine -match "gpu" }
        foreach ($process in $gpuProcesses) {
            $process.Kill()
            Write-ECRRLog "Stopped GPU monitoring process (PID: $($process.Id))"
        }
    } catch {
        Write-ECRRLog "No GPU monitoring processes to stop" "WARN"
    }
    
    # Clean up temporary files
    $tempFiles = @(
        ".artifacts/gpu-*.ps1",
        ".artifacts/gpu-*.log",
        "gpu-buffers/logs/test-*.jsonl"
    )
    
    foreach ($pattern in $tempFiles) {
        try {
            Get-ChildItem -Path $pattern -ErrorAction SilentlyContinue | Remove-Item -Force
            Write-ECRRLog "Cleaned up temporary files: $pattern"
        } catch {
            Write-ECRRLog "No files to clean up: $pattern" "WARN"
        }
    }
    
    return $true
}

