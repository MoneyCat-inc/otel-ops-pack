# GPU Integration Automation
# Integrates GPU sidecars into the existing automation workflow
# Provides seamless integration with monitoring, alerting, and reporting

param(
    [Parameter(Mandatory=$true)]
    [ValidateSet("integrate", "validate", "deploy", "monitor", "report", "cleanup")]
    [string]$Action,
    
    [switch]$IncludeExistingWorkflow,
    [switch]$IncludeScheduledTasks,
    [switch]$IncludeHealthChecks,
    [switch]$IncludeMetrics,
    [switch]$IncludeAlerts,
    [switch]$IncludeDashboard,
    [switch]$DryRun,
    [string]$Environment = "local"
)

# ECRR Framework Integration
$ECRRReport = @{
    Examine = @{}
    Clean = @{}
    Report = @{}
    Role = "GPU Integration Automation"
}

function Write-ECRRLog {
    param([string]$Message, [string]$Level = "INFO")
    $timestamp = Get-Date -Format "yyyy-MM-ddTHH:mm:ssZ"
    $logEntry = "[$timestamp] [$Level] $Message"
    Write-Host $logEntry -ForegroundColor $(if($Level -eq "ERROR"){"Red"}elseif($Level -eq "WARN"){"Yellow"}else{"Green"})
    $ECRRReport.Report[$timestamp] = $logEntry
}

function Test-ExistingWorkflowIntegration {
    Write-ECRRLog "Examining existing workflow integration..."
    
    $integration = @{
        scheduled_tasks = @{}
        monitoring_scripts = @{}
        health_checks = @{}
        alerting_systems = @{}
        dashboards = @{}
    }
    
    # Check existing scheduled tasks
    try {
        $existingTasks = Get-ScheduledTask -TaskName "*OTel*" -ErrorAction SilentlyContinue
        $integration.scheduled_tasks.count = $existingTasks.Count
        $integration.scheduled_tasks.tasks = $existingTasks | Select-Object TaskName, State
        Write-ECRRLog "Found $($existingTasks.Count) existing OTel scheduled tasks"
    } catch {
        Write-ECRRLog "Failed to check scheduled tasks: $($_.Exception.Message)" "ERROR"
    }
    
    # Check monitoring scripts
    $monitoringScripts = @(
        "scripts/monitor-optimized-pipeline.ps1",
        "scripts/quick-monitor.ps1",
        "scripts/production-monitoring.ps1",
        "scripts/robust-production-monitor.ps1"
    )
    
    foreach ($script in $monitoringScripts) {
        if (Test-Path $script) {
            $integration.monitoring_scripts[$script] = $true
            Write-ECRRLog "Found monitoring script: $script"
        }
    }
    
    # Check health check endpoints
    $healthEndpoints = @(
        @{Name="Collector"; URL="http://localhost:13134/healthz"},
        @{Name="SigNoz"; URL="http://localhost:8080/api/v1/health"},
        @{Name="GPU Compression"; URL="http://localhost:8001/health"},
        @{Name="GPU Aggregation"; URL="http://localhost:8002/health"},
        @{Name="GPU Inference"; URL="http://localhost:8003/health"}
    )
    
    foreach ($endpoint in $healthEndpoints) {
        try {
            $response = Invoke-WebRequest -Uri $endpoint.URL -UseBasicParsing -TimeoutSec 5
            $integration.health_checks[$endpoint.Name] = @{healthy = $true; status_code = $response.StatusCode}
            Write-ECRRLog "$($endpoint.Name) health check: HEALTHY"
        } catch {
            $integration.health_checks[$endpoint.Name] = @{healthy = $false; error = $_.Exception.Message}
            Write-ECRRLog "$($endpoint.Name) health check: UNHEALTHY" "ERROR"
        }
    }
    
    # Check alerting systems
    $alertingFiles = @(
        "alerts/signoz-alerts.json",
        "signoz-ecrr-canary-alert.json",
        "signoz-health-canary-alert.json",
        "signoz-metrics-canary-alert.json"
    )
    
    foreach ($file in $alertingFiles) {
        if (Test-Path $file) {
            $integration.alerting_systems[$file] = $true
            Write-ECRRLog "Found alerting configuration: $file"
        }
    }
    
    # Check dashboard configurations
    $dashboardFiles = @(
        "artifacts/signoz-gpu-sidecar-dashboard.json",
        "artifacts/signoz-dashboard-config.json"
    )
    
    foreach ($file in $dashboardFiles) {
        if (Test-Path $file) {
            $integration.dashboards[$file] = $true
            Write-ECRRLog "Found dashboard configuration: $file"
        }
    }
    
    $ECRRReport.Examine.Integration = $integration
    return $integration
}

