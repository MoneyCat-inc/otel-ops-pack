function Validate-GPUIntegration {
    Write-ECRRLog "Validating GPU integration..."
    
    $validation = @{
        sidecar_health = @{}
        workflow_integration = @{}
        monitoring_integration = @{}
        alerting_integration = @{}
        dashboard_integration = @{}
    }
    
    # Validate sidecar health
    $sidecars = @(
        @{Name="Compression"; Port=8001},
        @{Name="Aggregation"; Port=8002},
        @{Name="Inference"; Port=8003}
    )
    
    foreach ($sidecar in $sidecars) {
        try {
            $healthResponse = Invoke-WebRequest -Uri "http://localhost:$($sidecar.Port)/health" -UseBasicParsing -TimeoutSec 5
            if ($healthResponse.StatusCode -eq 200) {
                $healthData = $healthResponse.Content | ConvertFrom-Json
                $validation.sidecar_health[$sidecar.Name] = @{
                    healthy = $true
                    status = $healthData.status
                    gpu_available = $healthData.gpu_available
                }
            } else {
                $validation.sidecar_health[$sidecar.Name] = @{healthy = $false; error = "HTTP $($healthResponse.StatusCode)"}
            }
        } catch {
            $validation.sidecar_health[$sidecar.Name] = @{healthy = $false; error = $_.Exception.Message}
        }
    }
    
    # Validate workflow integration
    $workflowFiles = @(
        "scripts/enhanced-monitoring-with-gpu.ps1",
        "scripts/enhanced-scheduled-task.ps1"
    )
    
    foreach ($file in $workflowFiles) {
        $validation.workflow_integration[$file] = Test-Path $file
    }
    
    # Validate monitoring integration
    try {
        $monitoringTest = & pwsh -ExecutionPolicy Bypass -File "scripts/enhanced-monitoring-with-gpu.ps1" -IncludeGPU -DurationMinutes 1
        $validation.monitoring_integration.enhanced_script = $LASTEXITCODE -eq 0
    } catch {
        $validation.monitoring_integration.enhanced_script = $false
        $validation.monitoring_integration.error = $_.Exception.Message
    }
    
    # Validate alerting integration
    $validation.alerting_integration.gpu_alerts_config = Test-Path "alerts/gpu-alerts.json"
    
    # Validate dashboard integration
    $validation.dashboard_integration.gpu_dashboard = Test-Path "artifacts/signoz-gpu-sidecar-dashboard.json"
    
    $ECRRReport.Examine.Validation = $validation
    
    # Calculate overall validation score
    $totalChecks = 0
    $passedChecks = 0
    
    foreach ($category in $validation.Keys) {
        if ($validation[$category] -is [hashtable]) {
            foreach ($check in $validation[$category].Keys) {
                $totalChecks++
                if ($validation[$category][$check] -is [hashtable]) {
                    if ($validation[$category][$check].healthy) { $passedChecks++ }
                } elseif ($validation[$category][$check] -eq $true) {
                    $passedChecks++
                }
            }
        }
    }
    
    $validationScore = if ($totalChecks -gt 0) { ($passedChecks / $totalChecks) * 100 } else { 0 }
    Write-ECRRLog "GPU integration validation: $($validationScore.ToString('F1'))% ($passedChecks/$totalChecks checks passed)"
    
    return @{validation = $validation; score = $validationScore; passed = $passedChecks; total = $totalChecks}
}

function Deploy-GPUIntegration {
    Write-ECRRLog "Deploying GPU integration..."
    
    if ($DryRun) {
        Write-ECRRLog "DRY RUN: Would deploy GPU integration"
        return $true
    }
    
    # Deploy GPU sidecars
    try {
        $deployResult = docker-compose -f docker-compose.gpu.yml up -d
        if ($LASTEXITCODE -eq 0) {
            Write-ECRRLog "GPU sidecars deployed successfully"
        } else {
            Write-ECRRLog "GPU sidecar deployment failed" "ERROR"
            return $false
        }
    } catch {
        Write-ECRRLog "GPU sidecar deployment error: $($_.Exception.Message)" "ERROR"
        return $false
    }
    
    # Deploy enhanced monitoring
    if ($IncludeHealthChecks) {
        try {
            Start-Process -FilePath "pwsh" -ArgumentList @("-ExecutionPolicy", "Bypass", "-File", "scripts/enhanced-monitoring-with-gpu.ps1", "-IncludeGPU", "-IncludeGPUMetrics") -WindowStyle Hidden
            Write-ECRRLog "Enhanced monitoring deployed"
        } catch {
            Write-ECRRLog "Failed to deploy enhanced monitoring: $($_.Exception.Message)" "ERROR"
        }
    }
    
    # Deploy GPU metrics collection
    if ($IncludeMetrics) {
        try {
            Start-Process -FilePath "python" -ArgumentList @("gpu-metrics-simple.py", "--duration", "3600", "--interval", "15") -WindowStyle Hidden
            Write-ECRRLog "GPU metrics collection deployed"
        } catch {
            Write-ECRRLog "Failed to deploy GPU metrics collection: $($_.Exception.Message)" "ERROR"
        }
    }
    
    # Deploy GPU alerting
    if ($IncludeAlerts) {
        try {
            Start-Process -FilePath "pwsh" -ArgumentList @("-ExecutionPolicy", "Bypass", "-File", "scripts/gpu-automated-monitoring.ps1", "-EnableAlerting") -WindowStyle Hidden
            Write-ECRRLog "GPU alerting deployed"
        } catch {
            Write-ECRRLog "Failed to deploy GPU alerting: $($_.Exception.Message)" "ERROR"
        }
    }
    
    # Deploy GPU dashboard
    if ($IncludeDashboard) {
        try {
            $dashboardResult = & pwsh -ExecutionPolicy Bypass -File "scripts/import-dashboard.ps1" -DashboardFile "artifacts/signoz-gpu-sidecar-dashboard.json"
            if ($LASTEXITCODE -eq 0) {
                Write-ECRRLog "GPU dashboard deployed"
            } else {
                Write-ECRRLog "GPU dashboard deployment failed" "ERROR"
            }
        } catch {
            Write-ECRRLog "GPU dashboard deployment error: $($_.Exception.Message)" "ERROR"
        }
    }
    
    return $true
}

